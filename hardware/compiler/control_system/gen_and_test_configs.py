import os
import re
from collections import defaultdict


def _collapse_int_arrays(text: str) -> str:
    """Put arrays of integers (qubit lists, children) on one line, keeping the
    rest of the indented structure."""
    return re.sub(r"\[[\d,\s]+\]",
                  lambda m: re.sub(r"\s+", " ", m.group(0)).replace("[ ", "[").replace(" ]", "]"),
                  text)


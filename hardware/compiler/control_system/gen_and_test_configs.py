def make_config(name, leaf_qubits, router_groups=None, kern=None, postselect=()):
    kern = kern or {"count": 256, "n": 16, "h": 8}    # generous compact kernels (pass 1)
    leaves = [{"board_id": i, "qubits": ql, "kernels": dict(kern), "raw_out": 99999}
              for i, ql in enumerate(leaf_qubits)]
    layers = [{"level": 0, "type": "leaf", "boards": leaves}]
    if router_groups is None:
        layers.append({"level": 1, "type": "root", "boards": [
            {"board_id": 9999, "children": [b["board_id"] for b in leaves], "kernels": dict(kern)}]})
    else:
        routers = [{"board_id": 1000 + ri, "children": [leaves[i]["board_id"] for i in grp],
                    "kernels": dict(kern), "raw_out": 99999}
                   for ri, grp in enumerate(router_groups)]
        layers.append({"level": 1, "type": "router", "boards": routers})
        layers.append({"level": 2, "type": "root", "boards": [
            {"board_id": 9999, "children": [r["board_id"] for r in routers], "kernels": dict(kern)}]})
    return {"name": name, "version": 1, "hardware": {"layers": layers},
            "postselect": sorted(postselect)}


def tighten(cfg_dict, comp):
    """Size each board's kernels to its actual need (channel count / n / h) with a
    little headroom, using the compact uniform-kernel form for readability."""
    for layer in cfg_dict["hardware"]["layers"]:
        for b in layer["boards"]:
            ch = comp.programs[b["board_id"]].channels
            b["kernels"] = {
                "count": max(1, len(ch) + 1),
                "n": max((len(c.support) for c in ch), default=1) + 1,
                "h": max((c.required_h for c in ch), default=1) + 1,
            }
    cfg_dict["name"] += "_sized"


def configs_for(coords, postselect):
    return {
        "mono":   make_config("mono",   [_qubits(coords)], postselect=postselect),
        "strip2": make_config("strip2", partition_x(coords, 2), postselect=postselect),
        "strip4": make_config("strip4", partition_x(coords, 4), postselect=postselect),
        "grid4":  make_config("grid4",  partition_grid(coords, 2, 2), postselect=postselect),
        "tree3":  make_config("tree3",  partition_x(coords, 4), router_groups=[[0, 1], [2, 3]],
                              postselect=postselect),
    }



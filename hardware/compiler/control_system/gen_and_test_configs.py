if __name__ == "__main__":
    os.makedirs(DATA, exist_ok=True)
    results = []
    for cname, path in CIRCUITS.items():
        circuit = stim.Circuit.from_file(path)
        s = DetectorConstructionScanner.from_file(path)
        s.scan(); s.refine()
        coords = s._physical_qubits_coord_raw
        postselect = _load_postselect(cname)
        for shape, gen_dict in configs_for(coords, postselect).items():
            comp1 = Compiler(CompilerConfig(gen_dict), s)          # pass 1: generous
            tighten(gen_dict, comp1)                               # size kernels to need
            fn = f"{DATA}/config_{cname}_{shape}.json"
            with open(fn, "w") as f:
                f.write(_collapse_int_arrays(json.dumps(gen_dict, indent=2)))  # readable, sized
            cfg = CompilerConfig.from_file(fn)                     # pass 2: sized config
            comp = Compiler(cfg, s)
            feasible = all(not comp.programs[b].problems for b in cfg.boards)
            nboards = len(cfg.boards)
            depth = len(gen_dict["hardware"]["layers"])
            print("=" * 70)
            print(f"{cname} / {shape}: {nboards} boards, {depth} layers, feasible={feasible}")
            ok = run_test(circuit=circuit, comp=comp, shots=1000) if feasible else False
            results.append((cname, shape, nboards, depth, feasible, ok))

    print("\n" + "=" * 70 + "\nSUMMARY")
    print(f"{'circuit':7} {'shape':7} {'boards':6} {'layers':6} {'feasible':8} {'test'}")
    for c, sh, nb, dp, fe, ok in results:
        print(f"{c:7} {sh:7} {nb:<6} {dp:<6} {str(fe):8} {'PASS' if ok else 'FAIL'}")

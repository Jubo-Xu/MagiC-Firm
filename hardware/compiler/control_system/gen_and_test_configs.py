"""gen_and_test_configs.py — build several realistic compiler configs and run the
test harness on each, for both cultivation circuits.

Config shapes:
  mono    : 1 leaf (all qubits) + root                       (2 layers)
  strip2  : 2 leaves split by x                               (2 layers)
  strip4  : 4 leaves split by x                               (2 layers)
  grid4   : 4 leaves split by (x,y) into a 2x2 grid           (2 layers)
  tree3   : 4 x-strip leaves -> 2 routers -> root             (3 layers)
"""

